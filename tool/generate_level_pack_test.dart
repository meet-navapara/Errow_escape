// Generates, validates and writes all campaign levels:
//   assets/levels/levels_v1.txt            (the pack the game loads)
//   docs/level_validation_report.csv       (one row per level)
//   docs/level_validation_report.md        (summary)
//
//   flutter test tool/generate_level_pack_test.dart
//
// Fails without writing anything if any level is invalid, unsolvable or a
// duplicate (including rotations/reflections) of another level.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:arrow_escape/game/difficulty.dart';
import 'package:arrow_escape/game/level_generator.dart';
import 'package:arrow_escape/game/level_pack.dart';
import 'package:arrow_escape/game/level_validation.dart';
import 'package:arrow_escape/game/levels_data.dart';
import 'package:arrow_escape/game/puzzle_solver.dart';

void main() {
  test('generate level pack', () {
    final total = LevelsRepository.totalLevels;
    final lines = <String>[];
    final csv = StringBuffer(
      'level,difficulty,planned,breather,rows,cols,arrows,depth,'
      'initial_moves,blocking_pairs,avg_choices,score,solver_status,'
      'hint_legal,generated_ms\n',
    );
    final failures = <String>[];
    final keys = <String, int>{};
    final byBand = <Difficulty, List<int>>{};
    final sw = Stopwatch()..start();

    for (var id = 1; id <= total; id++) {
      final t0 = sw.elapsedMilliseconds;
      final board = LevelGenerator.generateLevel(id).board;
      final ms = sw.elapsedMilliseconds - t0;

      final issues = LevelValidation.problems(board);
      final key = LevelValidation.canonicalKey(board);
      final dup = keys[key];
      if (dup != null) issues.add('duplicate of level $dup');
      keys[key] = id;

      final a = PuzzleSolver.analyze(board);
      final hint = PuzzleSolver.getHint(board);
      final hintLegal = hint != null && board.checkEscape(hint.arrow).canEscape;
      if (!hintLegal) issues.add('hint is not a legal move');
      if (issues.isNotEmpty) failures.add('Level $id: ${issues.join('; ')}');

      final score = Difficulty.score(a);
      final difficulty = Difficulty.fromScore(score);
      byBand.putIfAbsent(difficulty, () => []).add(id);
      final info = LevelInfo(
        id: id,
        rows: board.rows,
        cols: board.cols,
        difficulty: difficulty,
        score: score,
        depth: a.depth,
        arrows: a.arrowCount,
        initialMoves: a.initialMoves,
        blockingPairs: a.blockingPairs,
      );
      lines.add(LevelPack.encode(board, info));
      csv.writeln(
        [
          id,
          difficulty.name,
          id > LevelGenerator.legacyLevelCount
              ? LevelGenerator.targetBandFor(id).name
              : 'legacy',
          LevelGenerator.isBreather(id),
          board.rows,
          board.cols,
          a.arrowCount,
          a.depth,
          a.initialMoves,
          a.blockingPairs,
          (a.arrowCount / a.depth).toStringAsFixed(2),
          score.toStringAsFixed(1),
          issues.isEmpty ? 'verified' : 'FAILED',
          hintLegal,
          ms,
        ].join(','),
      );
    }

    expect(failures, isEmpty, reason: failures.join('\n'));

    File(LevelPack.assetPath)
      ..createSync(recursive: true)
      ..writeAsStringSync(
        '# Arrow Escape level pack v${LevelPack.version}: '
        '$total levels, generated by tool/generate_level_pack_test.dart.\n'
        '# Format: see lib/game/level_pack.dart.\n'
        '${lines.join('\n')}\n',
      );
    File('docs/level_validation_report.csv')
      ..createSync(recursive: true)
      ..writeAsStringSync(csv.toString());

    final md = StringBuffer()
      ..writeln('# Level validation report')
      ..writeln()
      ..writeln(
        'Generated by `tool/generate_level_pack_test.dart` '
        '(pack v${LevelPack.version}). Per-level data: '
        '[level_validation_report.csv](level_validation_report.csv).',
      )
      ..writeln()
      ..writeln('- Levels: $total, verified solvable: $total, failures: 0')
      ..writeln(
        '- Duplicate check: ${keys.length} distinct puzzles '
        '(rotations and reflections count as duplicates)',
      )
      ..writeln('- First hint is a legal move on every level')
      ..writeln(
        '- Generation time: ${(sw.elapsedMilliseconds / 1000).round()} s',
      )
      ..writeln()
      ..writeln(
        '| Difficulty | Levels | Score range | Arrows (min-max) | Depth (min-max) |',
      )
      ..writeln('| --- | --- | --- | --- | --- |');
    for (final d in Difficulty.values) {
      final ids = byBand[d] ?? [];
      if (ids.isEmpty) continue;
      final infos = [
        for (final i in ids) LevelPack.parse(lines[i - 1]).info(i)!,
      ];
      String range(num Function(LevelInfo) f) {
        final v = infos.map(f).toList()..sort();
        return '${v.first}-${v.last}';
      }

      md.writeln(
        '| ${d.label} | ${ids.length} | ${range((i) => i.score)} | '
        '${range((i) => i.arrows)} | ${range((i) => i.depth)} |',
      );
    }
    File('docs/level_validation_report.md').writeAsStringSync(md.toString());
  }, timeout: const Timeout(Duration(minutes: 60)));
}
